"""Tests for the sliced 3MF parser (flashforge.threemf).

The fixtures under tests/fixtures/threemf are trimmed from real slicer output:
the real slice_info.config, the real G-code header and summary comments, a
1x1 placeholder plate image, and no toolpath. They keep the files at ~2 KB
while every value the parser reads is what the slicer actually wrote.
"""

from __future__ import annotations

import io
import zipfile
from pathlib import Path

import pytest

from flashforge import threemf
from flashforge.exceptions import FlashForgeError
from flashforge.threemf import (
    PrinterFamily,
    ThreeMFError,
    ThreeMFFormatError,
    ThreeMFMultiplePlatesError,
    ThreeMFNotSlicedError,
    parse_3mf,
    printer_family_from_model_id,
    translate_warning,
)

FIXTURES = Path(__file__).parent / "fixtures" / "threemf"

SLICE_INFO_TEMPLATE = """<?xml version="1.0" encoding="UTF-8"?>
<config>
  <plate>
    <metadata key="index" value="{index}"/>
    <metadata key="printer_model_id" value="{model}"/>
    <metadata key="prediction" value="600"/>
    <metadata key="weight" value="4.20"/>
    {filaments}
  </plate>
</config>
"""

GCODE_HEADER = """; HEADER_BLOCK_START
; generated by Orca-Flashforge 1.4.2 on 2025-11-12 at 17:40:16
; total layer number: 12
; HEADER_BLOCK_END

; filament used [mm] = 1000.00, 2500.00
; filament used [g] = 3.00, 7.50
; total filament used [g] = 10.50
; estimated printing time (normal mode) = 1h 2m 3s

; CONFIG_BLOCK_START
; filament_colour = #112233;#AABBCC
; filament_type = PLA;PETG
; printer_model = Flashforge AD5X
; CONFIG_BLOCK_END
; EXECUTABLE_BLOCK_START
G28
"""


def build_3mf(
    path: Path,
    *,
    slice_info: str | None = None,
    plates: dict[int, str] | None = None,
    thumbnail: bytes | None = b"\x89PNG-fake",
) -> Path:
    """Write a minimal 3MF archive for a test case."""
    plates = {1: GCODE_HEADER} if plates is None else plates
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("[Content_Types].xml", "<Types/>")
        if slice_info is not None:
            archive.writestr("Metadata/slice_info.config", slice_info)
        for index, gcode in plates.items():
            archive.writestr(f"Metadata/plate_{index}.gcode", gcode)
            if thumbnail is not None:
                archive.writestr(f"Metadata/plate_{index}.png", thumbnail)
    return path


def filament_xml(filament_id: int, material: str, color: str, grams: float) -> str:
    return (
        f'<filament id="{filament_id}" type="{material}" color="{color}" '
        f'used_m="1.00" used_g="{grams}" />'
    )


