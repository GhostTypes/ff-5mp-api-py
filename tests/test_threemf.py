def test_corrupt_entry(tmp_path):
    path = build_3mf(
        tmp_path / "t.3mf",
        slice_info=SLICE_INFO_TEMPLATE.format(
            index=1, model="x", filaments=filament_xml(1, "PLA", "#FFFFFF", 1)
        ),
    )
    data = bytearray(path.read_bytes())
    # Flip bytes inside the slice_info entry's compressed data.
    offset = data.index(b"Metadata/slice_info.config") + len("Metadata/slice_info.config") + 5
    for i in range(offset, offset + 20):
        data[i] ^= 0xFF
    path.write_bytes(bytes(data))

    with pytest.raises(ThreeMFFormatError):
        parse_3mf(path)


