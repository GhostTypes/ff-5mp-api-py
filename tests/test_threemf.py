def test_errors_share_the_library_base_class():
    assert issubclass(ThreeMFError, FlashForgeError)
    for error in (ThreeMFFormatError, ThreeMFNotSlicedError, ThreeMFMultiplePlatesError):
        assert issubclass(error, ThreeMFError)


