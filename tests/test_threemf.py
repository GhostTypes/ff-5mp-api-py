def test_only_used_filaments_are_listed_and_keep_their_ids(tmp_path):
    """A file that uses filament 3 alone maps tool 2, not tool 0."""
    slice_info = SLICE_INFO_TEMPLATE.format(
        index=1, model="Flashforge-AD5X", filaments=filament_xml(3, "PETG", "#00FF00", 2.5)
    )
    result = parse_3mf(build_3mf(tmp_path / "t.3mf", slice_info=slice_info))

    assert [(f.filament_id, f.tool_id) for f in result.filaments] == [(3, 2)]


def test_filaments_are_sorted_by_id(tmp_path):
    filaments = filament_xml(2, "PLA", "#000000", 1) + filament_xml(1, "PLA", "#FFFFFF", 1)
    slice_info = SLICE_INFO_TEMPLATE.format(index=1, model="x", filaments=filaments)

    result = parse_3mf(build_3mf(tmp_path / "t.3mf", slice_info=slice_info))

    assert [f.filament_id for f in result.filaments] == [1, 2]


def test_filament_without_a_valid_id_is_skipped(tmp_path):
    filaments = '<filament type="PLA" color="#FFFFFF" />' + filament_xml(1, "PLA", "#FFFFFF", 1)
    slice_info = SLICE_INFO_TEMPLATE.format(index=1, model="x", filaments=filaments)

    result = parse_3mf(build_3mf(tmp_path / "t.3mf", slice_info=slice_info))

    assert [f.filament_id for f in result.filaments] == [1]


