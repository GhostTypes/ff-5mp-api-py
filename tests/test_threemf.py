def test_orca_flashforge_130_single_color_5m_pro():
    result = parse_3mf(FIXTURES / "orca-flashforge-1.3.0_5mpro.3mf")

    assert result.file_name == "orca-flashforge-1.3.0_5mpro.3mf"
    assert result.plate_index == 1
    assert result.printer_model_id == "Flashforge-Adventurer-5M-Pro"
    assert result.printer_family is PrinterFamily.ADVENTURER_5M_PRO
    assert result.slicer_name == "Orca-Flashforge"
    assert result.slicer_version == "1.3.0"
    assert result.estimated_time_s == 433
    assert result.total_weight_g == pytest.approx(3.64)
    assert result.layer_count == 10
    assert result.support_used is False
    assert result.nozzle_diameters == [0.4]
    assert result.tool_count == 1
    filament = result.filaments[0]
    assert (filament.filament_id, filament.tool_id) == (1, 0)
    assert filament.material_name == "PLA"
    assert filament.color == "#C0C0C0"
    assert filament.used_g == pytest.approx(3.64)
    assert filament.used_m == pytest.approx(1.22)
    assert result.warnings == []
    assert result.thumbnail_png is not None
    assert result.thumbnail_png.startswith(b"\x89PNG")


